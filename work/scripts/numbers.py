def mde(n_control: float, n_test: float, base: float) -> float:
    """Минимальный заметный относительный прирост: мощность 80%, уровень 5%."""
    se = math.sqrt(base * (1 - base) * (1 / n_control + 1 / n_test))
    return 2.8 * se / base


