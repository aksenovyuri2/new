def fmt(r: dict) -> str:
    v, u = r["value"], r["unit"]
    if u == "доля":
        return f"{v * 100:.2f}%".replace(".", ",")
    if abs(v) >= 1_000_000:
        return f"{v / 1_000_000:.2f} млн".replace(".", ",")
    if abs(v) >= 1000:
        return f"{v / 1000:.1f}".replace(".", ",") + " тыс."
    return f"{v:.2f}".replace(".", ",")


